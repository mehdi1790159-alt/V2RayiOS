#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
source "${script_dir}/common.sh"

require_macos
require_command xcodebuild
require_command xcrun
require_command go
require_command zip
require_command ditto
require_source_layout

mobile_version="$(awk '$1 == "golang.org/x/mobile" { print $2; exit }' "${core_root}/go.mod")"
[[ -n "${mobile_version}" ]] || fail "could not determine golang.org/x/mobile version from ${core_root}/go.mod"

echo "V2RayiOS source: ${app_root}"
echo "v2ray-core source: ${core_root}"
echo "Build directory: ${build_root}"
echo "Pinned x/mobile: ${mobile_version}"
go version
xcodebuild -version
xcrun --sdk iphoneos --show-sdk-version

if [[ -d "${app_root}/V2binding.xcframework" ]]; then
    echo "Existing generated framework: ${app_root}/V2binding.xcframework"
else
    echo "V2binding.xcframework is absent and will be generated by build-v2binding.sh"
fi

